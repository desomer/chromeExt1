  function translate(value) {
    const trimmed = value.trim();
    let translated = translations[trimmed];
    if (!translated) {
      for (const [pattern, replacement] of dynamicTranslations) {
        const match = trimmed.match(pattern);
        if (match) {
          translated = replacement(match);
          break;
        }
      }
    }
    if (!translated || translated === trimmed) return value;
    return value.replace(trimmed, translated);
  }

  function localize(node) {
    if (node.nodeType === Node.TEXT_NODE) {
      if (!node.parentElement?.closest("script, style")) {
        const translated = translate(node.nodeValue);
        if (translated !== node.nodeValue) node.nodeValue = translated;
      }
      return;
    }
    if (node.nodeType !== Node.ELEMENT_NODE) return;
    for (const attribute of ["title", "placeholder", "aria-label"]) {
      if (node.hasAttribute(attribute)) {
        const oldValue = node.getAttribute(attribute);
        const translated = translate(oldValue);
        if (translated !== oldValue) node.setAttribute(attribute, translated);
      }
    }
    for (const child of node.childNodes) localize(child);
  }

